def load_client():
    path = SCRIPTS / "decidr_client.py"
    spec = importlib.util.spec_from_file_location("plan_anchor_decidr_client_test", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


class DecidrClientTests(unittest.TestCase):
    def setUp(self):
        self.client = load_client()
        self.old_agent = sys.modules.get("sc_agent")
        self.agent = types.ModuleType("sc_agent")
        class SagError(Exception):
            def __init__(self, identity):
                detail = identity if isinstance(identity, dict) else {"id": identity, "message": identity}
                super().__init__(detail.get("id", "unknown"))
                self.id = detail.get("id")
                self.message = detail.get("message")
                self.detail = detail
                self.category = detail.get("category", "other")
        self.agent.SagError = SagError
        self.agent.category = lambda detail: json.loads(detail).get("category", "other")
        self.agent.retryable = lambda detail: json.loads(detail).get("category") in {"busy", "network"}
        self.agent.logger = Mock(return_value={"ok": True, "value": object()})
        self.agent.Cancel = type("Cancel", (), {"cancel": Mock()})
        self.agent.parse_result = lambda line: parse_wheel_result(line, self.agent)
        sys.modules["sc_agent"] = self.agent
        self.consent = patch.object(self.client, "remote_preflight", return_value={"ok": True, "value": None})
        self.consent.start()
        self.addCleanup(self.consent.stop)

    def tearDown(self):
        if self.old_agent is None:
            sys.modules.pop("sc_agent", None)
        else:
            sys.modules["sc_agent"] = self.old_agent

    def test_client_records_sc_decidr_version(self):
        self.assertRegex(self.client.SC_DECIDR_VERSION, r"^\d+\.\d+\.\d+$")
        self.assertEqual(self.client.SC_DECIDR_VERSION, importlib.metadata.version("sc-decidr"))
        header = Path(self.client.__file__).read_text(encoding="utf-8").splitlines()[0]
        self.assertEqual(header, f"# Generated by sc-decidr {self.client.SC_DECIDR_VERSION}; Python >=3.11.")

    def test_client_is_fresh_render_of_shared_wheel_template(self):
        distribution = importlib.metadata.distribution("sc-decidr")
        template = Path(distribution.locate_file("sc_agent/templates/consumer.py.j2"))
        version = importlib.metadata.version("sc-decidr")
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            variables = root / "consumer.json"
            variables.write_text(json.dumps({"client_name": "plan-anchor", "sitr": False,
                                             "sc_decidr_version": version}), encoding="utf-8")
            output = root / "decidr_client.py"
            run_test_child(["sc-compose", "render", "--root", str(template.parent), "--file", template.name,
                            "--var-file", str(variables), "--strict", "--output", str(output)],
                           check=True, capture_output=True, text=True, encoding="utf-8")
            rendered = output.read_bytes()
            if not rendered.endswith(b"\n"):
                output.write_bytes(rendered + b"\n")
            self.assertEqual(Path(self.client.__file__).read_text(encoding="utf-8"),
                             output.read_text(encoding="utf-8"))

