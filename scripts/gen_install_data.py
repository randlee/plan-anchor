#!/usr/bin/env python3
"""Generate the installer's package data from the plugin tree and git history.

    python3 scripts/gen_install_data.py           # write both files
    python3 scripts/gen_install_data.py --check   # fail (exit 2) when either is stale
    python3 scripts/gen_install_data.py --render-neutral
        # after editing install/templates/: rewrite the committed tree as the
        # templates' neutral render (needs the sc-compose wheel)

plugins/sc-plan-anchor/install/manifest.json
    What this version installs: every skill file, the agents per harness, and
    which of them are rendered from install/templates/.

plugins/sc-plan-anchor/install/legacy-owned.json
    sha256 of every skill and agent file an earlier version shipped, keyed by
    its installed path, read from git history. install.py treats a file in a
    repository without an install lock as its own when the bytes match one of
    these, so a hand-vendored install migrates and retired files are removed.

History covers every commit reachable from BASE (0.6.0) plus EXTRA commits
that may not reach a branch here (0.4.2 was released from 8b33dd9; 0.6.1 is eba5b5a). A clone
without an EXTRA commit checks only what it can regenerate and says so.
Layouts: ``skills/.claude/skills/plan-anchoring/``, ``skills/.{claude,codex}/agents/``
(before the plugin layout) and ``plugins/sc-plan-anchor/{skills/plan-anchoring,.<harness>/agents}/``.
``registry.yaml`` is never installed and never listed.

Exit 0 on success; 2 when a file is stale (--check) or the script cannot do its
job (missing history, no sc-compose, a render failure). A check script's job is
to fail CI, so staleness is nonzero; like every plan-anchor CLI it never exits 1.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess
import sys
from typing import Dict, List, Optional, Set, Tuple

ROOT = Path(__file__).resolve().parent.parent
PLUGIN = ROOT / "plugins" / "sc-plan-anchor"
SKILL = PLUGIN / "skills" / "plan-anchoring"
TEMPLATES = PLUGIN / "install" / "templates"
MANIFEST = PLUGIN / "install" / "manifest.json"
LEGACY = PLUGIN / "install" / "legacy-owned.json"
TARGETS = ("claude", "codex", "cursor")
IGNORED = {"__pycache__", ".DS_Store"}
BASE = "79dd7a0"            # 0.6.0
EXTRA = ("8b33dd9", "eba5b5a")  # 0.4.2 (released from a commit no branch here contains); 0.6.1 (feat/anchor-exclude)
HEADER = "generated by scripts/gen_install_data.py; do not edit"
FAIL = 2  # stale output or a failure to generate; never 1

LAYOUTS: Tuple[Tuple[re.Pattern, str], ...] = (
    (re.compile(r"^skills/\.claude/skills/plan-anchoring/(?P<rel>.+)$"), "skill"),
    (re.compile(r"^plugins/sc-plan-anchor/skills/plan-anchoring/(?P<rel>.+)$"), "skill"),
    (re.compile(r"^skills/\.(?P<target>claude|codex)/agents/(?P<name>[^/]+\.md)$"), "agent"),
    (re.compile(r"^plugins/sc-plan-anchor/\.(?P<target>claude|codex|cursor)/agents/(?P<name>[^/]+\.md)$"), "agent"),
)


def _shown(path: Path) -> str:
    try:
        return path.relative_to(ROOT).as_posix()
    except ValueError:
        return str(path)


def _ignored(rel: str) -> bool:
    return bool(IGNORED & set(rel.split("/")))


def manifest() -> dict:
    skill = sorted(p.relative_to(SKILL).as_posix() for p in SKILL.rglob("*")
                   if p.is_file() and not _ignored(p.relative_to(SKILL).as_posix()))
    agents = {t: sorted(p.name for p in (PLUGIN / f".{t}" / "agents").glob("anchor-*.md")) for t in TARGETS}
    skill_templates = sorted(p.relative_to(TEMPLATES / "skills" / "plan-anchoring").as_posix()[: -len(".j2")]
                             for p in (TEMPLATES / "skills" / "plan-anchoring").rglob("*.j2"))
    agent_templates = sorted(p.name[: -len(".j2")] for p in (TEMPLATES / "agents").glob("*.j2"))
    return {"_comment": HEADER, "skill": skill, "agents": agents,
            "templates": {"skill": skill_templates, "agents": agent_templates}}


def _git(*args: str, stdin: Optional[bytes] = None) -> bytes:
    return subprocess.run(["git", "-C", str(ROOT), *args], input=stdin, capture_output=True, check=True).stdout


def _has_commit(rev: str) -> Optional[str]:
    done = subprocess.run(["git", "-C", str(ROOT), "rev-parse", "--verify", "--quiet", f"{rev}^{{commit}}"],
                          capture_output=True, text=True)
    return done.stdout.strip() if done.returncode == 0 else None


def history_commits() -> Tuple[List[str], List[str]]:
    """(commits read, EXTRA commits missing from this clone)."""
    base = _has_commit(BASE)
    if base is None:
        print(f"gen_install_data: base commit {BASE} is not in this clone; fetch full history "
              "(actions/checkout with fetch-depth: 0)", file=sys.stderr)
        raise SystemExit(FAIL)
    commits = _git("rev-list", base).decode().split()
    missing = []
    for rev in EXTRA:
        full = _has_commit(rev)
        if full is None:
            missing.append(rev)
        elif full not in commits:
            commits.append(full)
    return commits, missing


def legacy(commits: List[str]) -> dict:
    keyed: Dict[str, Set[str]] = {}   # blob id -> keys
    for commit in commits:
        for line in _git("ls-tree", "-r", commit).decode().splitlines():
            meta, path = line.split("\t", 1)
            _mode, kind, blob = meta.split()
            if kind != "blob":
                continue
            for pattern, kind_ in LAYOUTS:
                m = pattern.match(path)
                if not m:
                    continue
                if kind_ == "skill":
                    rel = m.group("rel")
                    if not _ignored(rel):
                        keyed.setdefault(blob, set()).add(f"skill\t{rel}")
                elif m.group("name") != "registry.yaml":
                    keyed.setdefault(blob, set()).add(f"agent\t{m.group('target')}\t{m.group('name')}")
                break
    blobs = sorted(keyed)
    out = _git("cat-file", "--batch", stdin="".join(b + "\n" for b in blobs).encode())
    skill: Dict[str, Set[str]] = {}
    agents: Dict[str, Dict[str, Set[str]]] = {t: {} for t in TARGETS}
    pos = 0
    for blob in blobs:
        nl = out.index(b"\n", pos)
        size = int(out[pos:nl].split()[2])
        data = out[nl + 1: nl + 1 + size]
        pos = nl + 1 + size + 1
        digest = hashlib.sha256(data).hexdigest()
        for key in keyed[blob]:
            parts = key.split("\t")
            if parts[0] == "skill":
                skill.setdefault(parts[1], set()).add(digest)
            else:
                agents[parts[1]].setdefault(parts[2], set()).add(digest)
    return {"_comment": HEADER,
            "skill": {k: sorted(v) for k, v in sorted(skill.items())},
            "agents": {t: {k: sorted(v) for k, v in sorted(agents[t].items())} for t in TARGETS}}


def _text(data: dict) -> str:
    return json.dumps(data, indent=2, sort_keys=False) + "\n"


def _subset(small: dict, big: dict) -> List[str]:
    """Entries of ``small`` that ``big`` lacks (legacy layout)."""
    gaps = []
    for rel, shas in small["skill"].items():
        gaps += [f"skill {rel} {s}" for s in shas if s not in big["skill"].get(rel, [])]
    for t in TARGETS:
        for name, shas in small["agents"][t].items():
            gaps += [f"{t} agent {name} {s}" for s in shas if s not in big["agents"].get(t, {}).get(name, [])]
    return gaps


def render_neutral() -> int:
    """Write the neutral render of every template over the committed plugin files."""
    import importlib.util
    spec = importlib.util.spec_from_file_location("sc_plan_anchor_install", PLUGIN / "install.py")
    inst = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = inst
    spec.loader.exec_module(inst)
    sc = inst.check_sc_compose()
    if isinstance(sc, inst.Err):
        print(f"gen_install_data: {sc.error.message}", file=sys.stderr)
        return FAIL
    version = json.loads((PLUGIN / "plugin.json").read_text(encoding="utf-8"))["version"]
    data = manifest()
    for rel in data["templates"]["skill"]:
        out = inst.render_template(sc.value, TEMPLATES / "skills" / "plan-anchoring" / f"{rel}.j2", "neutral", version)
        if isinstance(out, inst.Err):
            print(f"gen_install_data: {out.error.message}", file=sys.stderr)
            return FAIL
        (SKILL / rel).write_bytes(out.value.encode("utf-8"))
    for name in data["templates"]["agents"]:
        out = inst.render_template(sc.value, TEMPLATES / "agents" / f"{name}.j2", "neutral", version)
        if isinstance(out, inst.Err):
            print(f"gen_install_data: {out.error.message}", file=sys.stderr)
            return FAIL
        for target in TARGETS:
            path = PLUGIN / f".{target}" / "agents" / name
            front, _ = inst._split_frontmatter(path.read_text(encoding="utf-8"))
            path.write_bytes((front + out.value).encode("utf-8"))
    print("rewrote the committed tree as the templates' neutral render")
    return 0


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="exit 2 when a generated file is stale")
    parser.add_argument("--render-neutral", action="store_true",
                        help="rewrite committed files from install/templates/ (neutral render), then exit")
    args = parser.parse_args(argv)
    if args.render_neutral:
        return render_neutral()
    commits, missing = history_commits()
    want_manifest = _text(manifest())
    want_legacy = legacy(commits)
    if not args.check:
        if missing:
            print(f"gen_install_data: commits {', '.join(missing)} are not in this clone; refusing to write "
                  "an incomplete legacy-owned.json", file=sys.stderr)
            return FAIL
        MANIFEST.write_text(want_manifest, encoding="utf-8")
        LEGACY.write_text(_text(want_legacy), encoding="utf-8")
        print(f"wrote {_shown(MANIFEST)} and {_shown(LEGACY)} from {len(commits)} commits")
        return 0
    stale = []
    if not MANIFEST.is_file() or MANIFEST.read_text(encoding="utf-8") != want_manifest:
        stale.append(f"{_shown(MANIFEST)} is stale")
    have = json.loads(LEGACY.read_text(encoding="utf-8")) if LEGACY.is_file() else None
    if have is None:
        stale.append(f"{_shown(LEGACY)} is missing")
    elif not missing:
        if _text(have) != _text(want_legacy):
            stale.append(f"{_shown(LEGACY)} is stale")
    else:
        gaps = _subset(want_legacy, have)
        if gaps:
            stale.append(f"{_shown(LEGACY)} lacks {len(gaps)} historical entries, e.g. {gaps[0]}")
        print(f"gen_install_data: {', '.join(missing)} not in this clone; checked legacy-owned.json "
              "contains everything the available history ships", file=sys.stderr)
    for line in stale:
        print(f"gen_install_data: {line}; run python3 scripts/gen_install_data.py", file=sys.stderr)
    return FAIL if stale else 0


if __name__ == "__main__":
    sys.exit(main())
