#!/usr/bin/env python3
"""Build the derived pages of this site: reports index, diagrams index, announcements index.

Derived pages are build artifacts: pages.yml runs this at deploy time, so the
deployed site can never disagree with the committed sources. Never commit the
generated index.html files.

Sources:
  site/reports/**/*.html      date-stamped report files (YYYYMMDD-HHMMSS-name.html)
  site/diagrams/**/*.html     exported diagrams
  site/announcements/*.md     announcement sources: "# Title — Subtitle" and a
                              "**Released:** Month D, YYYY" line
  site/examples/*/README.md   one example each: "# Title", a "**Shows:** one line" line and a
                              "**Page:** [text](page.html)" line naming the page in that folder
                              (the page itself is built by scripts/build-examples.py)

Usage: python3 scripts/build-site.py
"""
from __future__ import annotations

import datetime as dt
import html
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SITE = ROOT / "site"

# Two naming schemes are in use across the fleet: the contract is
# YYYYMMDD-HHMMSS-name, but repos that publish one run per day use
# YYYYMMDD-<sequence>-name. Both must date correctly or the index sorts randomly.
STAMP = re.compile(r"^(\d{8})-(\d{6})-(.+)$")
DAY_SEQ = re.compile(r"^(\d{8})-(\d+)-(.+)$")
SHOWS = re.compile(r"^\*\*Shows:\*\*\s*(.+?)\s*$", re.MULTILINE)
PAGE = re.compile(r"^\*\*Page:\*\*\s*\[[^\]]*\]\(([^)\s]+)\)", re.MULTILINE)
RELEASED = re.compile(r"\*\*Released:\*\*\s*([A-Z][a-z]+ \d{1,2}, \d{4})")
TITLE = re.compile(r"^#\s+(.+?)\s*$", re.MULTILINE)
BANNER = "<!-- generated by scripts/build-site.py — do not edit -->"


def page(title: str, body: str) -> str:
    return f"""<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>{html.escape(title)}</title>
{BANNER}
  <style>
    body {{ font: 16px/1.55 -apple-system, BlinkMacSystemFont, "Segoe UI", system-ui, sans-serif;
           margin: 0 auto; max-width: 46rem; padding: 2.5rem 1.25rem; color: #1b1b1f; }}
    h1 {{ font-size: 1.6rem; margin: 0 0 .25rem; }}
    p.sub {{ color: #55565e; margin: 0 0 1.75rem; }}
    h2 {{ font-size: 1.05rem; margin: 2rem 0 .6rem; text-transform: uppercase;
          letter-spacing: .06em; color: #55565e; }}
    ul {{ padding-left: 1.1rem; }}
    li {{ margin: .3rem 0; }}
    a {{ color: #0b5fff; text-decoration: none; }}
    a:hover {{ text-decoration: underline; }}
    code {{ background: #f2f2f5; padding: .1rem .3rem; border-radius: 3px; font-size: .9em; }}
    .empty {{ color: #6b6b74; font-style: italic; }}
    footer {{ margin-top: 3rem; padding-top: 1rem; border-top: 1px solid #e6e6ea;
              color: #6b6b74; font-size: .85rem; }}
  </style>
</head>
<body>
<main>
{body}
</main>
</body>
</html>
"""


def nav(up: str = "../") -> str:
    """Links to the site's sections from a page one folder below the site root (every derived page is)."""
    return (f'<nav><a href="{up}index.html">Home</a> · <a href="{up}announcements/index.html">Announcements</a>'
            f' · <a href="{up}reports/index.html">Reports</a> · <a href="{up}examples/index.html">Examples</a>'
            f' · <a href="{up}diagrams/index.html">Diagrams</a></nav>')


def collect(pattern_glob: str) -> list[tuple[pathlib.Path, dt.datetime | None, int, str]]:
    """Date-stamped files under SITE, newest first. Undated files sort last.

    Returns (path, when, sequence, label). The sequence breaks ties between runs
    published on the same day under the YYYYMMDD-<seq>-name scheme.
    """
    out: list[tuple[pathlib.Path, dt.datetime | None, int, str]] = []
    for path in SITE.glob(pattern_glob):
        if path.name == "index.html" or path.suffix != ".html":
            continue
        when: dt.datetime | None = None
        seq = 0
        label = path.stem.replace("-", " ")
        stem = path.stem
        m = STAMP.match(stem)
        if m:
            try:
                when = dt.datetime.strptime(m.group(1) + m.group(2), "%Y%m%d%H%M%S")
            except ValueError:
                when = None
            label = m.group(3).replace("-", " ").replace("_", " ").title()
        else:
            m = DAY_SEQ.match(stem)
            if m:
                try:
                    when = dt.datetime.strptime(m.group(1), "%Y%m%d")
                    seq = int(m.group(2))
                except ValueError:
                    when = None
                label = m.group(3).replace("-", " ").replace("_", " ").title()
        out.append((path, when, seq, label))
    out.sort(key=lambda t: (t[1] is not None, t[1] or dt.datetime.min, t[2]), reverse=True)
    return out


def build_reports() -> int:
    items = collect("reports/**/*.html")
    if items:
        entries = "\n".join(
            f'      <li><a href="{html.escape(p.relative_to(SITE / "reports").as_posix())}">'
            f'{html.escape(label)}</a>'
            + (f' <span class="sub">{when:%Y-%m-%d}{f" · run {seq}" if seq else ""}</span>' if when else "")
            + "</li>"
            for p, when, seq, label in items
        )
        listing = f"    <ul>\n{entries}\n    </ul>"
    else:
        listing = '    <p class="empty">No reports yet.</p>'
    body = f"""    <h1>Reports</h1>
    <p class="sub">Date-stamped runs, newest first. Each file is self-contained HTML.</p>
{nav()}
    <h2>Integration reports</h2>
{listing}
    <footer>Generated from <code>site/reports/</code>. Report filenames are
    <code>YYYYMMDD-HHMMSS-name.html</code>; history is the accumulation of files.</footer>"""
    (SITE / "reports" / "index.html").write_text(page("Reports", body), encoding="utf-8")
    return len(items)


def build_diagrams() -> int:
    items = collect("diagrams/**/*.html")
    if items:
        entries = "\n".join(
            f'      <li><a href="{html.escape(p.relative_to(SITE / "diagrams").as_posix())}">{html.escape(label)}</a></li>'
            for p, _when, _seq, label in items
        )
        listing = f"    <ul>\n{entries}\n    </ul>"
    else:
        listing = ('    <p class="empty">No diagrams yet. Exported diagrams (self-contained '
                   'HTML, e.g. from a graph or Mermaid render) belong in <code>site/diagrams/</code>.</p>')
    body = f"""    <h1>Diagrams</h1>
    <p class="sub">Architecture and flow diagrams as browsable HTML.</p>
{nav()}
{listing}
    <footer>Generated from <code>site/diagrams/</code>.</footer>"""
    (SITE / "diagrams" / "index.html").write_text(page("Diagrams", body), encoding="utf-8")
    return len(items)


def build_announcements() -> int:
    rows: list[tuple[dt.date | None, str, pathlib.Path]] = []
    for md in sorted(SITE.glob("announcements/*.md")):
        text = md.read_text(encoding="utf-8")
        title = (TITLE.search(text).group(1) if TITLE.search(text) else md.stem).strip()
        when = None
        if (m := RELEASED.search(text)):
            try:
                when = dt.datetime.strptime(m.group(1), "%B %d, %Y").date()
            except ValueError:
                when = None
        rows.append((when, title, md))
    rows.sort(key=lambda r: (r[0] is not None, r[0] or dt.date.min), reverse=True)
    if rows:
        entries = "\n".join(
            f'      <li><a href="{html.escape(md.with_suffix(".html").name)}">{html.escape(title)}</a>'
            + (f' <span class="sub">{when:%B %-d, %Y}</span>' if when else "")
            + "</li>"
            for when, title, md in rows
        )
        listing = f"    <ul>\n{entries}\n    </ul>"
    else:
        listing = '    <p class="empty">No announcements yet.</p>'
    body = f"""    <h1>Announcements</h1>
    <p class="sub">Newest first. Markdown sources live in <code>site/announcements/</code>.</p>
{nav()}
{listing}
    <footer>Generated from <code>site/announcements/*.md</code>.</footer>"""
    (SITE / "announcements" / "index.html").write_text(page("Announcements", body), encoding="utf-8")
    return len(rows)


def build_examples() -> int:
    rows = []
    for md in sorted(SITE.glob("examples/*/README.md")):
        text = md.read_text(encoding="utf-8")
        title = (TITLE.search(text).group(1) if TITLE.search(text) else md.parent.name).strip()
        shows, target = SHOWS.search(text), PAGE.search(text)
        if not shows or not target:
            raise SystemExit(f"{md.relative_to(ROOT)} needs a '**Shows:** ...' line and a '**Page:** [text](page.html)' line")
        rows.append((md.parent.name, title, shows.group(1), target.group(1)))
    if rows:
        entries = "\n".join(
            f'      <li><a href="{html.escape(name)}/{html.escape(target)}">{html.escape(title)}</a><br>'
            f'{inline(html.escape(shows))} <span class="sub">(<a href="{html.escape(name)}/README.md">inputs and how to reproduce</a>)</span></li>'
            for name, title, shows, target in rows
        )
        listing = f"    <ul>\n{entries}\n    </ul>"
    else:
        listing = '    <p class="empty">No examples yet.</p>'
    body = f"""    <h1>Examples</h1>
    <p class="sub">Reports generated from real inputs checked in beside them, rebuilt at deploy by
    <code>scripts/build-examples.py</code>, so each matches the current scripts.</p>
{nav()}
{listing}
    <footer>Generated from <code>site/examples/*/README.md</code>.</footer>"""
    (SITE / "examples" / "index.html").write_text(page("Examples", body), encoding="utf-8")
    return len(rows)


def render_markdown_to_html(md: pathlib.Path) -> None:
    """Minimal, dependency-free rendering of an announcement source to HTML."""
    text = md.read_text(encoding="utf-8")
    out: list[str] = []
    in_list = False
    for raw in text.splitlines():
        line = raw.rstrip()
        if not line:
            if in_list:
                out.append("    </ul>")
                in_list = False
            continue
        if line.startswith("# "):
            out.append(f"    <h1>{html.escape(line[2:])}</h1>")
        elif line.startswith("## "):
            out.append(f"    <h2>{html.escape(line[3:])}</h2>")
        elif line.startswith(("- ", "* ")):
            if not in_list:
                out.append("    <ul>")
                in_list = True
            out.append(f"      <li>{inline(html.escape(line[2:]))}</li>")
        elif line.startswith(">"):
            out.append(f'    <blockquote>{inline(html.escape(line.lstrip("> ")))}</blockquote>')
        else:
            out.append(f"    <p>{inline(html.escape(line))}</p>")
    if in_list:
        out.append("    </ul>")
    body = "\n".join(out) + f"\n{nav()}"
    (md.with_suffix(".html")).write_text(page(md.stem, body), encoding="utf-8")


def inline(text: str) -> str:
    text = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", text)
    text = re.sub(r"`(.+?)`", r"<code>\1</code>", text)
    text = re.sub(r"\[(.+?)\]\((.+?)\)", r'<a href="\2">\1</a>', text)
    return text


def main() -> None:
    for sub in ("reports", "diagrams", "announcements", "examples"):
        (SITE / sub).mkdir(parents=True, exist_ok=True)
    (SITE / ".nojekyll").touch()
    for md in sorted(SITE.glob("announcements/*.md")):
        render_markdown_to_html(md)
    n_reports = build_reports()
    n_diagrams = build_diagrams()
    n_ann = build_announcements()
    n_examples = build_examples()
    print(f"OK: {n_reports} report(s), {n_diagrams} diagram(s), {n_ann} announcement(s), {n_examples} example(s)")


if __name__ == "__main__":
    main()
