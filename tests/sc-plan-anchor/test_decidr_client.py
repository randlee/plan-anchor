    def test_batch_maps_errors_cancels_and_forwards_callback(self):
        lines = [
            '{"position":0,"response":{"text":"one"}}',
            '{"position":1,"error":{"id":"http.auth","category":"auth","message":"authentication failed"}}',
        ]

        def send_batch(requests, *, on_result, **kwargs):
            return batch_result(reversed(lines), on_result)

        self.agent.send_batch = Mock(side_effect=send_batch)
        cancel = Mock()
        callback = Mock()
        out = self.client.call_batch_results(
            ["one", "two"], model="m", project="p", abort_on=frozenset({"auth"}), category_codes={"auth": "AUTH"}, cancel=cancel,
            workers=3, timeout_secs=30, on_result=callback,
        )
        self.assertTrue(out["ok"])
        self.assertEqual([json.loads(record["line"]) for record in out["value"]], [envelope(line) for line in lines])
        cancel.cancel.assert_called_once_with()
        self.assertEqual([json.loads(args.args[0]["line"]) for args in callback.call_args_list], [envelope(line) for line in reversed(lines)])
        self.assertNotIn("session_log", self.agent.send_batch.call_args.kwargs)
        self.assertNotIn("provider", self.agent.send_batch.call_args.kwargs)
        self.assertEqual(self.agent.send_batch.call_args.kwargs["workers"], 3)
        self.assertEqual(self.agent.send_batch.call_args.kwargs["timeout_secs"], 30)

    def test_invalid_limits_are_forwarded_once_and_returned_as_shared_errors(self):
        common = dict(model="m", project="p", abort_on=frozenset(),
                      category_codes={}, cancel=Mock())
        cases = (("send", "timeout_secs", -1, "decidr.invalid_request_timeout"),
                 ("send_batch", "timeout_secs", -1, "decidr.invalid_request_timeout"),
                 ("send_batch", "workers", 0, "decidr.invalid_workers"),
                 ("send_batch", "workers", -1, "decidr.invalid_workers"))
        for operation, option, value, error_id in cases:
            with self.subTest(operation=operation, option=option, value=value):
                error = self.agent.SagError(error_id)
                error.category = "validation"
                method = Mock(return_value={"ok": False, "error": {**error.detail, "category": error.category}})
                setattr(self.agent, operation, method)
                call_client = self.client.call_result if operation == "send" else self.client.call_batch_results
                request = "request" if operation == "send" else ["request"]
                result = call_client(request, **common, **{option: value})
                self.assertEqual(result["error"].data["id"], error_id)
                self.assertEqual(method.call_count, 1)
                self.assertEqual(method.call_args.kwargs[option], value)

    def test_error_values_do_not_call_removed_category_function(self):
        line = '{"position":0,"error":{"id":"auth","category":"auth","message":"authentication failed"}}'
        self.agent.category = Mock(wraps=self.agent.category)
        self.agent.send = Mock(return_value=line)
        common = dict(model="m", project="p", abort_on=frozenset(),
                      category_codes={"auth": "AUTH"}, cancel=Mock())
        self.client.call_result("request", **common)
        self.assertEqual(self.agent.category.call_count, 0)
        self.agent.category.reset_mock()
        def send_batch(requests, *, on_result, **kwargs):
            return batch_result([line], on_result)
        self.agent.send_batch = Mock(side_effect=send_batch)
        self.client.call_batch_results(["request"], **common)
        self.assertEqual(self.agent.category.call_count, 0)

